#!/usr/bin/env node
/**
 * Turns the HTML templates into a JS module the serverless function can import.
 *
 * A Vercel function cannot reliably read sibling files at runtime — the bundler
 * only ships what is imported — so the templates are compiled in instead. Run
 * this after editing anything in emails/.
 *
 *   npm run build:emails
 */

import { readFileSync, writeFileSync } from "node:fs"

const SOURCES = {
  passwordReset: "emails/password-reset.html",
  signInLink: "emails/sign-in-link.html",
  verifyEmail: "emails/verify-email.html",
}

const SUBJECTS = {
  passwordReset: "Reset your NEET Companion password",
  signInLink: "Your NEET Companion sign-in link",
  verifyEmail: "Confirm your email for NEET Companion",
}

/** Strips the authoring comments and BODY markers; keeps the markup itself. */
function clean(html) {
  const marked = html.match(/<!-- BODY -->\n([\s\S]*?)\n<!-- \/BODY -->/)
  const body = marked ? marked[1] : html.replace(/^<!--[\s\S]*?-->\s*/, "")
  return body.trim()
}

const out = [
  "// GENERATED by scripts/build-email-modules.mjs — do not edit.",
  "// Source of truth is emails/*.html. Re-run `npm run build:emails` after changing them.",
  "",
]

for (const [key, file] of Object.entries(SOURCES)) {
  const html = clean(readFileSync(file, "utf8"))
  if (!html.includes("%LINK%")) {
    console.error(`${file} has no %LINK% — the email would have nothing to click.`)
    process.exit(1)
  }
  out.push(`export const ${key} = {`)
  out.push(`  subject: ${JSON.stringify(SUBJECTS[key])},`)
  out.push(`  html: ${JSON.stringify(html)},`)
  out.push(`}`)
  out.push("")
}

writeFileSync("api/_templates.js", out.join("\n"))

console.log("wrote api/_templates.js")
for (const [key, file] of Object.entries(SOURCES)) {
  console.log(`  ${key.padEnd(15)} from ${file}`)
}
